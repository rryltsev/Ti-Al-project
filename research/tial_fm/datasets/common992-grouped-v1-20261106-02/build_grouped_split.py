"""Conservative fixed-composition parent grouping and paired DeepMD export.

No energies, forces, predictions or model errors enter the split optimization.
Exact liquid trajectory IDs remain unknown. The group invariant (nTi,nAl)
contains every trajectory generated by the archived fixed-species MD/relax code.
"""
from pathlib import Path
from collections import Counter, defaultdict
import argparse, csv, hashlib, json, platform, shutil, time
import numpy as np
import scipy
from scipy.optimize import Bounds, LinearConstraint, milp
from scipy.sparse import lil_matrix
from ase.io import read

ROOT=Path(__file__).resolve().parents[1]
WORK=ROOT.parents[1]
SOURCE=Path(r'C:\Users\Roman Ryltsev\Desktop\STARTUPS\Ti-Al-X\TiAl-Project')
PARTS=('train','validation','test')
XCS=('PBE','PBEsol','r2SCAN')
SEED=20261106
RATIOS=np.array([.70,.15,.15])

def digest(p):
    h=hashlib.sha256()
    with Path(p).open('rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
    return h.hexdigest()

def dump(p,value):
    p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text(json.dumps(value,indent=2,ensure_ascii=False)+'\n',encoding='utf8')

def group_key(r):return (r['composition'].get('Ti',0),r['composition'].get('Al',0))
def group_id(k):return f'fixed-species-Ti{k[0]}-Al{k[1]}'
def family(r):
    return {'unresolved_liquid_relax_pool':'liquid_relax','POSCAR_alpha-Ti-hcp_orthogonal':'hcp','POSCAR_beta-Ti-bcc':'bcc','POSCAR_gamma_AlTi_L1_0':'gamma'}[r['structural_family']]
def bin_id(r):return min(4,int(5*r['composition'].get('Al',0)/r['natoms']))

def features(r):
    f=family(r);b=bin_id(r)
    return ['total','family:'+f,'composition_bin:'+str(b),'family_bin:'+f+':'+str(b),'natoms:'+str(r['natoms'])]

def assign(groups,records):
    names=sorted({s for r in records for s in features(r)})
    group_names=sorted(groups);fi={s:i for i,s in enumerate(names)}
    a=np.zeros((len(names),len(groups)))
    for j,k in enumerate(group_names):
        for r in groups[k]:
            if len(r['labels'])==3:
                for s in features(r):a[fi[s],j]+=1
    n=len(group_names);nf=len(names);nx=3*n;nv=nx+3*nf
    rows=[];lower=[];upper=[]
    def add(coef,lo,hi):rows.append(coef);lower.append(lo);upper.append(hi)
    for g in range(n):add({3*g+s:1 for s in range(3)},1,1)
    target=[694,149,149]
    for s in range(3):add({3*g+s:a[fi['total'],g] for g in range(n)},target[s],target[s])
    # Keep pure liquid end members available for learning elemental references.
    for g,k in enumerate(group_names):
        if k in [(216,0),(0,216)]:add({3*g:1},1,1)
    for i,name in enumerate(names):
        for s in range(3):
            desired=a[i].sum()*RATIOS[s];d=nx+3*i+s
            co={3*g+s:a[i,g] for g in range(n) if a[i,g]}
            add({**co,d:-1},-np.inf,desired)
            add({k:-v for k,v in co.items()}|{d:-1},-np.inf,-desired)
            if name.startswith('family:') or name.startswith('composition_bin:'):
                add(co,1,np.inf)
    mat=lil_matrix((len(rows),nv))
    for i,r in enumerate(rows):
        for j,v in r.items():mat[i,j]=v
    c=np.zeros(nv);c[:nx]=np.random.default_rng(SEED).uniform(0,1e-6,nx)
    for i,name in enumerate(names):
        weight=2 if name.startswith('family:') else 1
        for s in range(3):c[nx+3*i+s]=weight/max(3,a[i].sum()*RATIOS[s])
    lo=np.zeros(nv);hi=np.full(nv,np.inf);hi[:nx]=1
    integrality=np.zeros(nv);integrality[:nx]=1
    result=milp(c,integrality=integrality,bounds=Bounds(lo,hi),constraints=LinearConstraint(mat.tocsr(),lower,upper),options={'time_limit':30,'mip_rel_gap':.005})
    if result.x is None:raise RuntimeError('No feasible grouped assignment: '+result.message)
    z=np.rint(result.x[:nx]).astype(int).reshape(n,3)
    assert np.all(z.sum(axis=1)==1)
    mapping={k:PARTS[int(z[j].argmax())] for j,k in enumerate(group_names)}
    assert [sum(a[fi['total'],j] for j,k in enumerate(group_names) if mapping[k]==s) for s in PARTS]==target
    return mapping,{'method':'scipy.optimize.milp HiGHS','seed':SEED,'scipy':scipy.__version__,'objective':'Absolute deviations from 70/15/15 over source families, five Al-fraction bins, family×bin and natoms; no model/label values','target_counts':dict(zip(PARTS,target)),'status':int(result.status),'message':result.message,'mip_gap':float(result.mip_gap),'objective_value':float(result.fun),'group_assignment_frozen_in_splits':True}

def export(out,records,assignments):
    cache={};source_files={};files={};index=[]
    for xc in XCS:
        for part in PARTS:
            subset=defaultdict(list)
            for r in records:
                if len(r['labels'])==3 and assignments[group_key(r)]==part:subset[group_key(r)].append(r)
            for key,items in sorted(subset.items()):
                system=out/'deepmd'/xc/part/group_id(key);arr=system/'set.000';arr.mkdir(parents=True)
                arrays=defaultdict(list);ids=[]
                for r in sorted(items,key=lambda x:x['geometry_id']):
                    lab=r['labels'][xc];coord=Path(lab['coord_path']);source_system=coord.parent.parent
                    if str(coord) not in cache:
                        raw=np.loadtxt(source_system/'type.raw',dtype=int,ndmin=1)
                        names=(source_system/'type_map.raw').read_text().split();syms=[names[t] for t in raw]
                        perm=np.argsort([0 if s=='Al' else 1 for s in syms],kind='stable')
                        cache[str(coord)]=(syms,perm,{k:np.load(coord.with_name(k+'.npy'),allow_pickle=False) for k in ['coord','box','energy','force','virial']})
                        for p in [source_system/'type.raw',source_system/'type_map.raw']+[coord.with_name(k+'.npy') for k in ['coord','box','energy','force','virial']]:source_files[str(p)]=digest(p)
                    syms,perm,data=cache[str(coord)];i=lab['frame_index'];n=len(syms)
                    assert Counter(syms)==r['composition']
                    for k in ['coord','force']:arrays[k].append(data[k][i].reshape(n,3)[perm].reshape(-1))
                    for k in ['box','energy','virial']:arrays[k].append(np.asarray(data[k][i]).reshape(-1))
                    ids.append(r['geometry_id'])
                    index.append({'functional':xc,'split':part,'geometry_id':r['geometry_id'],'group_id':group_id(key),'system':str(system.relative_to(out)),'row':len(ids)-1,'source_coord_path':str(coord),'source_frame_index':i,'source_permutation_to_Al_Ti':perm.tolist()})
                (system/'type_map.raw').write_text('Al\nTi\n',encoding='utf8')
                np.savetxt(system/'type.raw',[0]*key[1]+[1]*key[0],fmt='%d')
                dump(system/'geometry_ids.json',ids)
                for k,values in arrays.items():
                    a=np.array(values);assert np.isfinite(a).all();np.save(arr/(k+'.npy'),a)
            dump(out/'deepmd'/xc/(part+'_systems.json'),[str((out/'deepmd'/xc/part/group_id(k)).resolve()) for k in sorted(subset)])
    for p in (out/'deepmd').rglob('*'):
        if p.is_file():files[str(p.relative_to(out))]={'sha256':digest(p),'bytes':p.stat().st_size}
    dump(out/'export_index.json',index);dump(out/'export_hashes.json',files);dump(out/'label_source_hashes.json',source_files)
    return {'geometry_functional_pairs':len(index),'files':len(files),'bytes':sum(r['bytes'] for r in files.values()),'type_map':['Al','Ti'],'geometry_policy':'Original native DFT coordinates/cells retained. Only stable species sort; identical permutation applied to forces. No energy shifts, recalculation or precision reduction.','cross_XC_geometry_identity':'Same verified physical geometry ID; source coordinate rounding retained, not forced to bitwise equality.'}

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--version',default='common992-grouped-v1-20261106-02');args=ap.parse_args()
    out=ROOT/'datasets'/args.version;out.mkdir(parents=True,exist_ok=False);start=time.perf_counter()
    source=ROOT/'runs/initial-audit-20261106-01/data_manifest.jsonl'
    records=[json.loads(l) for l in source.read_text(encoding='utf8').splitlines()]
    groups=defaultdict(list)
    for r in records:groups[group_key(r)].append(r)
    assert len(records)==1000 and sum(len(r['labels'])==3 for r in records)==992
    # Initial POSCARs are evidence of possible starts, never invented trajectory IDs.
    base=SOURCE/'MACE-dataset-gen/MD-liquid+relax';candidate=defaultdict(list);evidence={str(source):digest(source),str(Path(__file__)):digest(Path(__file__))}
    for p in sorted((base/'RESULT').glob('*/*/POSCAR')):
        atoms=read(p,format='vasp');c=Counter(atoms.get_chemical_symbols());key=(c['Ti'],c['Al']);h=digest(p)
        candidate[key].append({'path':str(p),'sha256':h});evidence[str(p)]=h
    for p in [base/'mace_md_npt_relax.py',base/'mace_md_npt_relax_mod.py',base/'cranberrer_get_structures.py',base/'multy_run_mace_md_npt_relax.sh',WORK/'testset/trajectory_audit.json']:
        evidence[str(p)]=digest(p);shutil.copyfile(p,out/p.name)
    # The retained initial POSCAR collection is incomplete. Missing candidates
    # do not justify inventing parent IDs or weakening the containment group.
    missing_initial_groups=[group_id(k) for k,v in groups.items() if any(family(r)=='liquid_relax' for r in v) and not candidate[k]]
    dump(out/'initial_parent_coverage.json',{'initial_POSCARs':sum(map(len,candidate.values())),'missing_candidate_groups':missing_initial_groups,'interpretation':'Candidate starts only; even a unique composition match is not proof of exact ancestry.'})
    assignment,opt=assign(groups,records)
    group_records=[]
    for key,items in sorted(groups.items()):
        group_records.append({'group_id':group_id(key),'n_Ti':key[0],'n_Al':key[1],'natoms':sum(key),'split':assignment[key],'paired_geometry_ids':sorted(r['geometry_id'] for r in items if len(r['labels'])==3),'incomplete_geometry_ids':sorted(r['geometry_id'] for r in items if len(r['labels'])!=3),'known_trajectory_ids':sorted({p for r in items for p in r['parent_ids']}),'possible_liquid_initial_POSCARs':candidate[key],'identity_claim':'Conservative parent containment group, not a recovered exact trajectory ID'})
    ids={s:sorted(r['geometry_id'] for r in records if len(r['labels'])==3 and assignment[group_key(r)]==s) for s in PARTS}
    split={'version':args.version,'created_local_date':'2026-11-06','seed':SEED,'ratios_requested':dict(zip(PARTS,RATIOS.tolist())),'pool':'992 geometries with PBE/PBEsol/r2SCAN labels; original selected pool only','group_definition':'exact atom-count pair (n_Ti,n_Al), across all source families','guarantee':'No fixed-species, fixed-natoms MD trajectory or relaxation descendant can cross these partitions. Exact trajectory/frame IDs are not reconstructed.','assumptions':['Archived generator changes chemical species only before independent MD launches','MD and relaxation preserve nTi and nAl; no atom insertion/deletion/transmutation','The selected pool follows the documented generator; unrecorded variable-composition trajectories are outside this guarantee'],'tradeoff':'Potentially independent trajectories of identical composition are grouped together; validation/test exclude exact atom-count compositions present in train. This tests composition transfer as well as trajectory transfer.','archive49_policy':'Kept separate as historical diagnostic; not any new split and not used for tuning. Parent overlaps with new partitions may exist.','split_ids':ids,'incomplete_labels_policy':'8 geometries excluded from paired benchmark, but assigned to their existing group role in auxiliary manifest. Never place an available label across group boundaries.','optimizer':opt,'training_policy':'Retrain all compared methods from common pretrained initialization or declared random initialization. Historical TiAl FT models saw many new test geometries and are not valid independent test baselines.'}
    dump(out/'splits.json',split);dump(out/'groups.json',group_records)
    manifest=[]
    for r in records:
        m={**r,'benchmark_version':args.version,'group_id':group_id(group_key(r)),'split':assignment[group_key(r)],'paired_benchmark_eligible':len(r['labels'])==3,'legacy_splits':{xc:l['split'] for xc,l in r['labels'].items()}}
        manifest.append(m)
    (out/'data_manifest.jsonl').write_text(''.join(json.dumps(r,ensure_ascii=False)+'\n' for r in manifest),encoding='utf8')
    with (out/'split_assignments.csv').open('w',newline='',encoding='utf8') as f:
        names=['geometry_id','group_id','split','paired_benchmark_eligible','natoms','n_Ti','n_Al','source_family','known_parent_ids'];w=csv.DictWriter(f,fieldnames=names);w.writeheader()
        for r in manifest:w.writerow({k:r[k] for k in names[:5]}|{'n_Ti':r['composition'].get('Ti',0),'n_Al':r['composition'].get('Al',0),'source_family':family(r),'known_parent_ids':'|'.join(r['parent_ids'])})
    export_summary=export(out,records,assignment)
    summary={}
    for s in PARTS:
        rr=[r for r in records if len(r['labels'])==3 and assignment[group_key(r)]==s]
        summary[s]={'geometries':len(rr),'groups':len({group_key(r) for r in rr}),'atoms':sum(r['natoms'] for r in rr),'geometry_functional_labels':len(rr)*3,'atom_functional_labels':sum(r['natoms'] for r in rr)*3,'source_families':dict(Counter(family(r) for r in rr)),'natoms':dict(Counter(r['natoms'] for r in rr)),'Al_fraction_bins':dict(Counter(bin_id(r) for r in rr)),'Al_fraction_range':[min(group_key(r)[1]/r['natoms'] for r in rr),max(group_key(r)[1]/r['natoms'] for r in rr)]}
    # Independent leakage accounting at the known-parent and conservative levels.
    parent_roles=defaultdict(set)
    for r in manifest:
        for p in r['parent_ids']:parent_roles[p].add(r['split'])
    assert all(len(v)==1 for v in parent_roles.values())
    assert all(not set(ids[a])&set(ids[b]) for i,a in enumerate(PARTS) for b in PARTS[i+1:])
    dump(out/'summary.json',{'version':args.version,'counts':summary,'conservative_groups_all_pool':len(groups),'known_parents':len(parent_roles),'known_parent_cross_split_overlaps':0,'conservative_group_cross_split_overlaps':0,'geometry_id_cross_split_overlaps':0,'original_liquid_trajectory_ids_recovered':False,'new_DFT_jobs':0,'new_training_jobs':0,'export':export_summary,'elapsed_seconds':time.perf_counter()-start,'versions':{'python':platform.python_version(),'numpy':np.__version__,'scipy':scipy.__version__}})
    dump(out/'input_hashes.json',evidence)
    shutil.copyfile(Path(__file__),out/'build_grouped_split.py')
    print(json.dumps(read_json(out/'summary.json'),indent=2))

